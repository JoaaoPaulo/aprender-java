public class Decisoes {
    public static void main(String[] args) {
        int horasEstudo = 10;

        if(horasEstudo >= 15){
            System.out.println("Dedicação máxima! Vai dominar Java rápido.");
        } else if(horasEstudo >= 5){
            System.out.println("Ótimo ritmo! A constância é a chave.");
        } else{
            System.out.println("Atenção! Tente dedicar pelo menos 5 horas por semana.");
        }
        
    }
}
